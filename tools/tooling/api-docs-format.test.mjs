/** Keeps transient generated references out of formatting without exempting authored Markdown. */
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative } from 'node:path';
import test from 'node:test';
import { check } from 'prettier';

const require = createRequire(import.meta.url);
// Use the installed CLI so ignore discovery matches the workspace formatter.
const prettier = require.resolve('prettier/bin/prettier.cjs');
// API Documenter emits CRLF Markdown and expanded HTML tables before any formatting.
const generatedReference = [
  '<!-- Do not edit this file. It is automatically generated by API Documenter. -->',
  '',
  '[Home](./index.md) &gt; [sh-ast](./sh-ast.md)',
  '',
  '<table><thead><tr><th>',
  '',
  'Symbol',
  '',
  '',
  '</th></tr></thead>',
  '<tbody><tr><td>',
  '',
  'parseSync',
  '',
  '',
  '</td></tr>',
  '</tbody></table>',
  '',
].join('\r\n');

/** Check only the controlled path, with the same root configuration and ignores as check:format. */
function format(path) {
  const result = spawnSync(process.execPath, [prettier, '--check', relative(process.cwd(), path)], {
    encoding: 'utf8',
  });
  assert.equal(result.error, undefined);
  assert.notEqual(result.status, null);
  console.log(`Prettier exit ${result.status}: ${path}\n${result.stdout}${result.stderr}`);
  return result;
}

test('temporary generated API reference pages do not fail workspace formatting', async () => {
  assert.equal(await check(generatedReference, { parser: 'markdown' }), false);
  const output = mkdtempSync(join(import.meta.dirname, '.api-docs-'));
  try {
    const page = join(output, 'reference.md');
    writeFileSync(page, generatedReference);
    const result = format(page);
    assert.equal(result.status, 0, result.stdout + result.stderr);
  } finally {
    rmSync(output, { recursive: true, force: true });
  }
});

test('ordinary handwritten Markdown formatting errors remain rejected', () => {
  const output = mkdtempSync(join(import.meta.dirname, '.format-control-'));
  try {
    const page = join(output, 'handwritten.md');
    writeFileSync(page, '# Handwritten\n\n|Name|Meaning|\n|---|---|\n|example|value|\n');
    const result = format(page);
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.ok((result.stdout + result.stderr).includes('handwritten.md'));
  } finally {
    rmSync(output, { recursive: true, force: true });
  }
});
