// Source identity is provenance for generated declarations, not a release label.
// A replacement must be named because its source may differ under the same
// original mvdan/sh requirement; local unversioned replacements are unverifiable.
package main

import (
	"strings"
	"testing"

	"golang.org/x/tools/go/packages"
)

func TestSyntaxSourceIdentity(t *testing.T) {
	for _, fixture := range []struct {
		name   string
		module *packages.Module
		want   string
	}{
		{"upstream", &packages.Module{Path: "mvdan.cc/sh/v3", Version: "v3.14.1"}, "mvdan.cc/sh/v3@v3.14.1"},
		{"fork", &packages.Module{Path: "mvdan.cc/sh/v3", Version: "v3.14.1", Replace: &packages.Module{
			Path: "github.com/mike-north/sh/v3", Version: "v3.14.2-0.20261105000000-0123456789ab",
		}}, "github.com/mike-north/sh/v3@v3.14.2-0.20261105000000-0123456789ab"},
	} {
		t.Run(fixture.name, func(t *testing.T) {
			got, err := syntaxSourceIdentity(fixture.module)
			if err != nil || got != fixture.want {
				t.Fatalf("source identity = %q, %v; want %q", got, err, fixture.want)
			}
		})
	}
}

func TestSyntaxSourceIdentityRejectsUnversionedSource(t *testing.T) {
	for _, module := range []*packages.Module{
		nil,
		{Path: "mvdan.cc/sh/v3"},
		{Path: "mvdan.cc/sh/v3", Version: "v3.14.1", Replace: &packages.Module{Path: "../local"}},
	} {
		if got, err := syntaxSourceIdentity(module); err == nil {
			t.Fatalf("unversioned source unexpectedly identified as %q", got)
		}
	}
}

// Generated provenance names the selected source directly, not an original
// release label followed by a second potentially conflicting dependency name.
func TestFaithfulHeaderNamesSelectedSource(t *testing.T) {
	const source = "github.com/mike-north/sh/v3@v3.14.2-0.20261106043227-bbc7c4ace575"
	header := faithfulHeader(&faithfulSchema{License: "BSD"}, source)
	const expected = "// Code generated by tools/gen-visitor-keys from " + source + ". DO NOT EDIT.\n"
	if !strings.HasPrefix(header, expected) {
		t.Fatalf("incorrect generated source identity: %s", header)
	}
}
